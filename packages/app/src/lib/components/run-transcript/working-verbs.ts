// Pick uniformly from every label except the one currently displayed.
export function nextWorkingVerbIndex(previous = -1, random = Math.random): number {
  const hasPrevious = previous >= 0 && previous < workingVerbs.length;
  const index = Math.floor(random() * (workingVerbs.length - (hasPrevious ? 1 : 0)));
  return hasPrevious && index >= previous ? index + 1 : index;
}
