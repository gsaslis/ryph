test("a body that is not JSON is the unknown signal, for every format", () => {
  for (const kind of WEBHOOK_FORMAT_KINDS) {
    const format: WebhookFormat = kind === "custom"
      ? {
        kind,
        mapping: { status: ["s"], firing: ["x"], resolved: [], update: [], key: [], title: [] },
      }
      : { kind };
    for (const body of ["not json", "", "null", "42", '"firing"', "[1,2]"]) {
      assertEquals(readSignal(format, body, {}), { status: "unknown", key: null, title: null });
    }
  }
});

test("a custom mapping: paths in order, values case-insensitive, unlisted values unknown", () => {
  const mapping: SignalMapping = {
    status: ["check.state", "state"],
    firing: ["DOWN"],
    resolved: ["up"],
    update: ["degraded"],
    key: ["check.id", "id"],
    title: ["check.name"],
  };
  const format = { kind: "custom", mapping } as const;
  assertEquals(read(format, { check: { state: "down", id: 17, name: "Homepage" } }), {
    status: "firing",
    key: "17", // a number becomes a string key
    title: "Homepage",
  });
  assertEquals(read(format, { state: " Up ", id: "c-1" }), {
    status: "resolved",
    key: "c-1",
    title: null,
  });
  assertEquals(read(format, { state: "degraded" }).status, "update");
  assertEquals(read(format, { state: "paused" }).status, "unknown");
  // A non-string status is not a status; the next path is tried.
  assertEquals(read(format, { check: { state: 1 }, state: "down" }).status, "firing");
});

test("keys and titles are folded to one line, trimmed, capped at 200, and null when empty", () => {
  const mapping: SignalMapping = {
    status: [],
    firing: [],
    resolved: [],
    update: [],
    key: ["k"],
    title: ["t"],
  };
  const signal = applyMapping({ k: "  a\n b\t\tc  ", t: "x".repeat(500) }, mapping);
  assertEquals(signal.key, "a b c");
  assertEquals(signal.title, "x".repeat(200));
  assertEquals(applyMapping({ k: "   ", t: "\n" }, mapping), {
    status: "unknown",
    key: null,
    title: null,
  });
  // Objects, booleans, null and non-finite numbers are not keys.
  for (const k of [{}, [], true, null]) {
    assertEquals(applyMapping({ k }, mapping).key, null);
  }
  // The cap counts code points, so an emoji is never split in half.
  assertEquals(applyMapping({ t: "😀".repeat(300) }, mapping).title, "😀".repeat(200));
});

test("paths: dots, indexes, quoted keys, and everything malformed", () => {
  const doc = {
    a: { b: [{ c: "deep" }, { c: "second" }] },
    "a.b": { c: "dotted" },
    'q"uote': 1,
    "0": "zero-key",
    list: ["first"],
  };
  assertEquals(valueAt(doc, "a.b[0].c"), "deep");
  assertEquals(valueAt(doc, "a.b[1].c"), "second");
  assertEquals(valueAt(doc, '["a.b"].c'), "dotted");
  assertEquals(valueAt(doc, '["a.b"]["c"]'), "dotted");
  assertEquals(valueAt(doc, 'a["b"][0].c'), "deep");
  assertEquals(valueAt(doc, '["q\\"uote"]'), 1);
  assertEquals(valueAt(doc, "list[0]"), "first");
  // No implicit conversions: a key segment never indexes an array, an index never keys an
  // object.
  assertEquals(valueAt(doc, "0"), "zero-key");
  assertEquals(valueAt(doc, "list.0"), undefined);
  assertEquals(valueAt({ x: { "0": "y" } }, "x[0]"), undefined);
  // Out of range, through a primitive, through null, an inherited key.
  assertEquals(valueAt(doc, "list[5]"), undefined);
  assertEquals(valueAt(doc, "a.b[0].c.d"), undefined);
  assertEquals(valueAt({ a: null }, "a.b"), undefined);
  assertEquals(valueAt({}, "constructor"), undefined);
  assertEquals(valueAt({}, "__proto__"), undefined);

  for (const bad of ["", ".", "a.", ".a", "a..b", "a[", "a[]", "a[-1]", "a[x]", 'a["b]', "a[0]b"]) {
    assertEquals(parsePath(bad), null, bad);
  }
  assertEquals(parsePath('a.b[0]["c.d"]'), [
    { key: "a" },
    { key: "b" },
    { index: 0 },
    { key: "c.d" },
  ]);
});

test("the preset table: every format listed once, and which read keys", () => {
  assertEquals(FORMAT_PRESETS.map((p) => p.kind).sort(), [...WEBHOOK_FORMAT_KINDS].sort());
  const pasted = FORMAT_PRESETS.filter((p) => p.secret === "pasted").map((p) => p.kind);
  assertEquals(pasted.sort(), ["incident-io", "pagerduty", "sentry"]);
  assertEquals(
    FORMAT_PRESETS.find((p) => p.kind === "alertmanager")!.verification,
    { kind: "secret-header", header: "authorization", prefix: "Bearer " },
  );
  assertEquals(formatYieldsKeys({ kind: "raw" }), false);
  assertEquals(formatYieldsKeys({ kind: "grafana" }), true);
  const custom = (key: string[]): WebhookFormat => ({
    kind: "custom",
    mapping: { status: [], firing: [], resolved: [], update: [], key, title: [] },
  });
  assertEquals(formatYieldsKeys(custom([])), false);
  assertEquals(formatYieldsKeys(custom(["id"])), true);

  assertEquals(defaultCorrelation({ kind: "schedule" }), "fire");
  assertEquals(defaultCorrelation({ kind: "webhook", format: { kind: "pagerduty" } }), "key");
  assertEquals(defaultCorrelation({ kind: "webhook", format: { kind: "raw" } }), "automation");
  assertEquals(defaultCorrelation({ kind: "webhook", format: custom([]) }), "automation");
  assertEquals(defaultCorrelation({ kind: "webhook", format: custom(["id"]) }), "key");
});
