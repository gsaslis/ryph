// --- incident.io ---------------------------------------------------------------------------

test("incident.io: the object under the event-named key, per event type", () => {
  const format = { kind: "incident-io" } as const;
  const id = "01FDAG4SAP5TYPT98WGR2N7W91";
  const created = {
    event_type: "public_incident.incident_created_v2",
    "public_incident.incident_created_v2": {
      id,
      reference: "INC-123",
      name: "Our database is sad",
      incident_status: { category: "live", name: "Investigating" },
      severity: { name: "Minor" },
      permalink: "https://app.incident.io/incidents/123",
    },
  };
  assertEquals(read(format, created), { status: "firing", key: id, title: "Our database is sad" });

  const statusUpdated = (category: string) => ({
    event_type: "public_incident.incident_status_updated_v2",
    "public_incident.incident_status_updated_v2": {
      incident: { id, name: "Our database is sad" },
      previous_status: { category: "live" },
      new_status: { category, name: "Post-incident" },
      message: "Fixed",
    },
  });
  assertEquals(read(format, statusUpdated("learning")), {
    status: "resolved",
    key: id,
    title: "Our database is sad",
  });
  assertEquals(read(format, statusUpdated("closed")).status, "resolved");
  assertEquals(read(format, statusUpdated("paused")).status, "update");
  assertEquals(read(format, statusUpdated("triage")).status, "firing");

  const alert = (eventType: string, status?: string) => ({
    event_type: eventType,
    [eventType]: {
      id: "01ALERT",
      ...(status === undefined ? {} : { status }),
      title: "Checkout latency",
      deduplication_key: "checkout",
    },
  });
  assertEquals(read(format, alert("public_alert.alert_created_v1", "firing")), {
    status: "firing",
    key: "01ALERT",
    title: "Checkout latency",
  });
  assertEquals(
    read(format, alert("public_alert.alert_resolved_v1", "resolved")).status,
    "resolved",
  );
  // No `status` on the alert: the event type says which.
  assertEquals(read(format, alert("public_alert.alert_resolved_v1")).status, "resolved");

  // A private incident carries only its id — still a key, nothing more.
  assertEquals(
    read(format, {
      event_type: "private_incident.incident_created_v2",
      "private_incident.incident_created_v2": { id },
    }),
    { status: "unknown", key: id, title: null },
  );
  // An event that is not incident or alert lifecycle, and a missing object.
  assertEquals(
    read(format, { event_type: "public_incident.follow_up_created_v1", x: {} }),
    { status: "unknown", key: null, title: null },
  );
});

