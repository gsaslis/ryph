// Payload formats: each preset read over the vendor's own payloads (firing, resolved, and a
// lifecycle update where the vendor has one), as each vendor documents them;
// the path syntax's edges; a custom mapping; and the promise that reading never throws.

import { test } from "bun:test";
import { assertEquals } from "@std/assert";
import {
  applyMapping,
  defaultCorrelation,
  type FireSignal,
  FORMAT_PRESETS,
  formatYieldsKeys,
  parsePath,
  readSignal,
  type SignalMapping,
  valueAt,
  WEBHOOK_FORMAT_KINDS,
  type WebhookFormat,
} from "../src/core/formats.ts";

const read = (
  format: WebhookFormat,
  body: unknown,
  headers: Record<string, string> = {},
): FireSignal =>
  readSignal(format, typeof body === "string" ? body : JSON.stringify(body), headers);

