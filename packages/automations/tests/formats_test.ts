const ALERTMANAGER_FIRING = {
  version: "4",
  groupKey: '{}/{severity="page"}:{alertname="HighErrorRate"}',
  truncatedAlerts: 0,
  status: "firing",
  receiver: "ryph",
  groupLabels: { alertname: "HighErrorRate" },
  commonLabels: { alertname: "HighErrorRate", severity: "page", service: "api" },
  commonAnnotations: { summary: "5xx rate above 5%" },
  externalURL: "http://am:9093",
  alerts: [{
    status: "firing",
    labels: { alertname: "HighErrorRate", service: "api", instance: "a" },
    annotations: { summary: "5xx rate above 5%" },
    startsAt: "2026-10-13T10:00:00Z",
    endsAt: "0001-01-01T00:00:00Z",
    generatorURL: "http://prom/graph?...",
    fingerprint: "c4a1e0b2d9f3a7e1",
  }],
};

test("alertmanager: firing and resolved by top-level status, keyed by groupKey", () => {
  const format = { kind: "alertmanager" } as const;
  const key = '{}/{severity="page"}:{alertname="HighErrorRate"}';
  assertEquals(read(format, ALERTMANAGER_FIRING), {
    status: "firing",
    key,
    title: "HighErrorRate",
  });
  assertEquals(read(format, { ...ALERTMANAGER_FIRING, status: "resolved" }), {
    status: "resolved",
    key,
    title: "HighErrorRate",
  });
  // The title falls back down its list: no common alertname → the group's → the summary → the
  // first alert's.
  const { commonLabels: _, ...noCommon } = ALERTMANAGER_FIRING;
  assertEquals(read(format, noCommon).title, "HighErrorRate");
  assertEquals(
    read(format, { ...noCommon, groupLabels: {} }).title,
    "5xx rate above 5%",
  );
  assertEquals(
    read(format, { ...noCommon, groupLabels: {}, commonAnnotations: {} }).title,
    "HighErrorRate",
  );
  // Alertmanager has no lifecycle beyond the two; anything else is unknown.
  assertEquals(read(format, { ...ALERTMANAGER_FIRING, status: "pending" }).status, "unknown");
});

